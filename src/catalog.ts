const weaponNotes = (w: W) => {
  const tag = w[3].split(" · ");
  const mastery = MASTERY[tag[0]] ? `Мастерство: ${tag[0]}` : "";
  return [w[1], w[2], mastery, tag.find((t) => t.startsWith("стиль") || t.startsWith("огнестр")), w[6] ? "книга DC" : ""]
    .filter((x) => x && x !== "—")
    .join(" · ");
};

