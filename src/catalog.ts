/** Предметы, к которым применим магический бонус +1/+2/+3 */
export const ENCHANTABLE: CatKey[] = ["weapon", "ammo", "armor", "shield"];
const RARITY = ["", "необычный", "редкий", "очень редкий", "легендарный"];
/** Редкость +N по DMG 2024: оружие/боеприпасы/щит +1 необычный…+3 очень редкий; доспех +1 редкий…+3 легендарный */
export function enchant(cat: CatKey, bonus: number) {
  const r = RARITY[bonus + (cat === "armor" ? 1 : 0)];
  if (cat === "weapon") return `+${bonus} к броскам атаки и урона (${r})`;
  if (cat === "ammo") return `+${bonus} к броскам атаки и урона; после попадания перестаёт быть магическим (${r})`;
  return `+${bonus} к КД (${r}) — в Challenge Mode: и к AR при методе DC`;
}

